    fun getPage(pageNumber: Int): TauzihPage {
        // Return exact page if available in curated database
        pageDatabase[pageNumber]?.let { return it }

        // Otherwise find the chapter containing this page and provide intelligent context
        val chapter = chapters.find { pageNumber in it.pageStart..it.pageEnd }
            ?: chapters.first()

        val approxMasla = if (chapter.pageEnd > chapter.pageStart) {
            val ratio = (pageNumber - chapter.pageStart).toFloat() / (chapter.pageEnd - chapter.pageStart)
            val estMasla = chapter.maslaStart + (ratio * (chapter.maslaEnd - chapter.maslaStart)).toInt()
            "مسئلہ نمبر $estMasla کے قریب"
        } else {
            "مسئلہ ${chapter.maslaStart} تا ${chapter.maslaEnd}"
        }

        return TauzihPage(
            pageNumber = pageNumber,
            chapterTitleUrdu = chapter.titleUrdu,
            chapterTitleEnglish = chapter.titleEnglish,
            masailRange = approxMasla,
            subHeadings = listOf(chapter.titleUrdu, chapter.category),
            contentUrdu = """
کتاب: توضیح المسائل (حضرت آیت اللہ العظمیٰ سید علی حسینی سیستانی)
باب: ${chapter.titleUrdu} (${chapter.titleEnglish})
صفحہ نمبر: $pageNumber (کل صفحات: ۵۴۲)
مسائل: ${chapter.maslaStart} تا ${chapter.maslaEnd}

خلاصہ و احکام:
${chapter.description}

اس صفحے کے متعلق تفصیلی فقہی احکام دریافت کرنے کے لئے AI چیٹ بوٹ سے کوئی بھی سوال پوچھیں یا ابواب کی فہرست میں سے متعلقہ مسئلہ ملاحظہ فرمائیں۔
            """.trimIndent(),
            primaryMasail = listOf()
        )
    }

    fun findChapterForPage(pageNumber: Int): TauzihChapter? {
        return chapters.find { pageNumber in it.pageStart..it.pageEnd }
    }

    fun search(query: String): List<TauzihChapter> {
        val q = query.trim().lowercase()
        if (q.isEmpty()) return chapters
        return chapters.filter { chapter ->
            chapter.titleUrdu.contains(q) ||
            chapter.titleEnglish.lowercase().contains(q) ||
            chapter.titleFarsi.contains(q) ||
            chapter.titleArabic.contains(q) ||
            chapter.description.contains(q) ||
            chapter.category.lowercase().contains(q) ||
            q.toIntOrNull()?.let { num ->
                num in chapter.maslaStart..chapter.maslaEnd || num in chapter.pageStart..chapter.pageEnd
            } == true
        }
    }
